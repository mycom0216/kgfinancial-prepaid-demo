-- 처음 켤 때 사용자, 카드, 기록, 결제 주문을 저장할 표를 만들어요.
CREATE TABLE demo_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE demo_cards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES demo_users(id),
    balance BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE demo_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    card_id BIGINT NOT NULL REFERENCES demo_cards(id),
    kind VARCHAR(20) NOT NULL,
    amount BIGINT NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_transaction_request UNIQUE(user_id, idempotency_key)
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(40) NOT NULL,
    action VARCHAR(60) NOT NULL,
    target VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE payment_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    card_id BIGINT NOT NULL REFERENCES demo_cards(id),
    amount BIGINT NOT NULL,
    pay_type VARCHAR(10) NOT NULL,
    status VARCHAR(24) NOT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    provider_tid VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_payment_idempotency UNIQUE(user_id, idempotency_key)
);
CREATE INDEX ix_cards_owner ON demo_cards(owner_id);
CREATE INDEX ix_transactions_card_created ON demo_transactions(card_id, created_at);
CREATE INDEX ix_payment_status_created ON payment_orders(status, created_at);

