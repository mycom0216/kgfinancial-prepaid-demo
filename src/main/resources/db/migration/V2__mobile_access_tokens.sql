-- 휴대폰 앱 로그인 열쇠의 지문과 만료시각을 저장해요. 원래 열쇠는 저장하지 않아요.
CREATE TABLE mobile_access_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES demo_users(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_mobile_tokens_user_expiry ON mobile_access_tokens(user_id, expires_at);

